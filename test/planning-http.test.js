import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { DateTime } from 'luxon';
import { Store } from '../src/store.js';
import { AcademicService } from '../src/service.js';
import { createApp } from '../src/server.js';
import { planningOutput } from '../src/planning-schema.js';
import { validate } from '../src/records.js';

test('study-plan GET/POST previews work without a model and never write or fetch', async t => {
  const store = new Store(':memory:');
  let fetches = 0;
  const service = new AcademicService(store, { frenchStartDate: '2026-01-01' }, async () => { fetches++; throw new Error('offline'); }, () => DateTime.fromISO('2026-10-21T08:00:00', { zone: 'Europe/Paris' }));
  const server = createApp(service, 0);
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(async () => { server.close(); server.closeAllConnections(); await once(server, 'close'); store.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const html = await (await fetch(base)).text();
  assert.ok(html.includes('id="planning-form"'));
  assert.ok(html.includes('id="planning-sessions"'));
  const asset = await fetch(`${base}/planning.js`);
  assert.equal(asset.status, 200);
  assert.ok(asset.headers.get('content-type').includes('javascript'));
  const token = html.match(/name="csrf-token" content="([^"]+)"/)[1];
  const headers = { Origin: base, 'X-CSRF-Token': token, 'Content-Type': 'application/json' };
  let response = await fetch(`${base}/api/study-plan?days=1&subject=Algebra&minutes=120`);
  let plan = await response.json();
  assert.equal(response.status, 200);
  validate(planningOutput, plan);
  assert.equal(plan.availability, 'unavailable');
  assert.equal(plan.sessions.length, 0);
  store.saveSync('BEGIN:VCALENDAR\r\nVERSION:2.0\r\nEND:VCALENDAR', '2026-10-21T06:00:00Z');
  const changes = () => store.db.prepare('SELECT total_changes() AS n').get().n;
  const before = changes();
  response = await fetch(`${base}/api/study-plan?days=1&subject=Algebra&minutes=120`);
  plan = await response.json();
  assert.equal(response.headers.get('cache-control'), 'no-store');
  validate(planningOutput, plan);
  assert.equal(plan.summary.plannedMinutes, 120);
  response = await fetch(`${base}/api/study-plan`, { method: 'POST', headers, body: JSON.stringify({ days: 1, subject: 'Temporary preview', minutes: 120, preferences: { dailyLimitMinutes: 60 } }) });
  const preview = await response.json();
  assert.equal(response.status, 200);
  validate(planningOutput, preview);
  assert.equal(preview.summary.plannedMinutes, 60);
  assert.equal(preview.summary.requestedShortfallMinutes, 60);
  assert.equal(service.planningPolicy.dailyLimitMinutes, 180);
  assert.equal(changes(), before);
  assert.equal(service.records.list('assignments').total, 0);
  assert.equal(service.records.list('exams').total, 0);
  assert.equal(fetches, 0);
  for (const query of ['days=15', 'days=no', 'days=1&days=2', 'date=tomorrow', 'date=2026-02-30', 'minutes=1.5', 'confirmed=true', '__proto__=bad']) assert.equal((await fetch(`${base}/api/study-plan?${query}`)).status, 400);
  const body = JSON.stringify({ subject: 'Study', preferences: { windows: [{ start: '20:00', end: '08:00' }] } });
  assert.equal((await fetch(`${base}/api/study-plan`, { method: 'POST', headers, body })).status, 400);
  assert.equal((await fetch(`${base}/api/study-plan`, { method: 'POST', headers: { ...headers, Origin: 'https://evil.example' }, body: '{}' })).status, 403);
  assert.equal((await fetch(`${base}/api/study-plan`, { method: 'POST', headers: { ...headers, 'X-CSRF-Token': '' }, body: '{}' })).status, 403);
  assert.equal((await fetch(`${base}/api/study-plan`, { method: 'POST', headers, body: '{invalid' })).status, 400);
  for (const method of ['PATCH', 'DELETE']) assert.equal((await fetch(`${base}/api/study-plan`, { method, headers, body: '{}' })).status, 405);
  assert.equal(changes(), before);
  service.suggestStudyPlan = () => { throw new Error('Private synthetic error SECRET'); };
  response = await fetch(`${base}/api/study-plan`);
  assert.equal(response.status, 500);
  assert.ok(!(await response.text()).includes('SECRET'));
});
