import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { DateTime } from 'luxon';
import { Store } from '../src/store.js';
import { AcademicService } from '../src/service.js';
import { createApp } from '../src/server.js';
import { overviewOutput } from '../src/overview.js';
import { validate } from '../src/records.js';

test('dashboard API works offline, reflects persistent CRUD immediately and is read-only', async t => {
  const store = new Store(':memory:');
  let fetches = 0;
  const service = new AcademicService(store, { frenchStartDate: '2026-01-01', refreshMinutes: 15 }, async () => { fetches++; throw new Error('offline'); }, () => DateTime.fromISO('2026-10-20T10:00:00', { zone: 'Europe/Paris' }));
  const server = createApp(service, 0);
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(async () => {
    server.close(); server.closeAllConnections(); await once(server, 'close');
    store.close();
  });
  const base = `http://127.0.0.1:${server.address().port}`;
  const page = await (await fetch(base)).text();
  assert.ok(page.includes('id="dashboard"'));
  assert.ok(page.includes('data-page="dashboard" aria-current="page"'));
  const token = page.match(/name="csrf-token" content="([^"]+)"/)[1];
  const headers = { Origin: base, 'X-CSRF-Token': token, 'Content-Type': 'application/json' };
  const asset = await fetch(`${base}/dashboard.js`);
  assert.equal(asset.status, 200);
  assert.ok(asset.headers.get('content-type').includes('javascript'));
  for (const file of ['ui.js', 'shell.js']) {
    const module = await fetch(`${base}/${file}`);
    assert.equal(module.status, 200);
    assert.ok(module.headers.get('content-type').includes('javascript'));
  }
  const font = await fetch(`${base}/fonts/manrope.ttf`);
  assert.equal(font.headers.get('content-type'), 'font/ttf');
  const bytes = Buffer.from(await font.arrayBuffer());
  assert.equal(bytes.readUInt32BE(0), 0x00010000, 'Font must be served as binary TrueType, not decoded UTF-8');
  assert.ok(bytes.length > 100000);
  const license = await (await fetch(`${base}/fonts/OFL.txt`)).text();
  assert.ok(license.includes('SIL OPEN FONT LICENSE'));
  assert.equal((await fetch(`${base}/favicon.svg`)).headers.get('content-type'), 'image/svg+xml; charset=utf-8');
  let response = await fetch(`${base}/api/overview`);
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('cache-control'), 'no-store');
  const empty = await response.json();
  validate(overviewOutput, empty);
  assert.equal(empty.calendar.hasCache, false);
  for (const query of ['date=tomorrow', 'limit=10', 'calendarUrl=SECRET']) assert.equal((await fetch(`${base}/api/overview?${query}`)).status, 400);
  const created = await (await fetch(`${base}/api/assignments`, { method: 'POST', headers, body: JSON.stringify({ title: 'Dashboard deadline', dueDate: '2026-10-20' }) })).json();
  const changeCount = () => store.db.prepare('SELECT total_changes() AS count').get().count;
  const before = changeCount();
  const overview = await (await fetch(`${base}/api/overview`)).json();
  assert.equal(overview.today.assignments[0].id, created.id);
  assert.equal(overview.needsAttention.approachingAssignments.length, 1);
  assert.equal(changeCount(), before);
  const completed = await fetch(`${base}/api/assignments/${created.id}/complete`, { method: 'POST', headers, body: JSON.stringify({ version: created.version }) });
  assert.equal(completed.status, 200);
  const after = await (await fetch(`${base}/api/overview`)).json();
  assert.equal(after.needsAttention.approachingAssignments.length, 0);
  assert.equal(after.today.assignments[0].status, 'completed');
  assert.equal(fetches, 0);
  assert.equal((await fetch(`${base}/api/overview`, { method: 'POST', headers, body: '{}' })).status, 404);
  service.overview = () => { throw new Error('Synthetic private error SECRET'); };
  response = await fetch(`${base}/api/overview`);
  assert.equal(response.status, 500);
  assert.ok(!(await response.text()).includes('SECRET'));
});
